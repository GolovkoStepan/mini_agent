# Оценочные задачи: прогон агента на воспроизводимых задачах ради ответа
# «стало лучше / хуже / не повлияло» после смены настроек сэмплинга.
#
# В гем не входит и из lib/mini_agent.rb не подключается: это инструмент
# разработки, живущий рядом с репозиторием, а не часть того, что ставится
# пользователю. Отсюда и собственное пространство имён Evals вместо
# MiniAgent::Evals — вложенное имя обещало бы, что оно поставляется вместе
# с агентом.
#
# Прогон идёт ЧЕРЕЗ exe/mini_agent, а не через классы агента напрямую.
# Дороже (процесс на прогон), но меряет то, что запускает человек: разбор
# флагов, сборку промпта, коды возврата. Замер по внутренним объектам
# показывал бы работу тех объектов, которые мы подставили сами.
module Evals
  # Сколько наблюдений на набор нужно, чтобы вообще произносить вердикт.
  #
  # Порог назван числом и проверяется явно, а не оставлен на усмотрение
  # оценки разброса: при одном прогоне на набор формула честно посчитает
  # «1 из 1 против 0 из 1» отличием, и отчёт объявит победителя по одному
  # наблюдению. Ошибка тем опаснее, что выглядит как измерение.
  MIN_OBSERVATIONS = 5
end
