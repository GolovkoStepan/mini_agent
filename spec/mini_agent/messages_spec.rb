# frozen_string_literal: true

# Спека на тексты нужна ровно в одном месте: там, где строка — это вход
# модели, а не оформление терминала. Всё, что уходит в Messages::Tool,
# читается моделью как часть данных, и правка «для красоты» здесь меняет
# поведение агента.
RSpec.describe MiniAgent::Messages do
  # Диапазоны значков, а не список конкретных: снятые ❌ ⛔ 🔁 📋 ⏱️ вернулись
  # бы под другими кодами, и точный перечень поймал бы только их.
  let(:emoji) { /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}]/ }

  def constants(mod)
    mod.constants.map { |name| [name, mod.const_get(name)] }.select { |(_, value)| value.is_a?(String) }
  end

  describe "строки, уходящие в модель" do
    # Системный промпт запрещает эмодзи, а эти строки ложатся модели
    # в контекст на каждом отказе — то есть учили бы ровно обратному.
    # Подражание контексту у небольшой сети сильнее прямого указания.
    it "не содержат ни одного значка" do
      constants(described_class::Tool).each do |name, text|
        expect(text).not_to match(emoji), "#{name} содержит эмодзи"
      end
    end

    # Отказы модель читает как успех, если не сказать прямо, что ничего
    # не произошло: живая проверка на `echo "мир" > b.txt` при политике ask
    # дала ответ «Файл b.txt создан». Снятие значка не должно было тронуть
    # ни одного слова — тест закрепляет именно слова.
    it "объясняют отказ, а не только называют его" do
      expect(described_class::Tool::CANCELLED).to include("НЕ выполнялась", "ничего не изменилось")
      expect(described_class::Tool::PLAN_REFUSED).to include("НЕ выполнялась", "ничего не изменилось")
    end
  end

  describe "системный промпт" do
    it "не содержит значков" do
      expect(described_class::SYSTEM_PROMPT).not_to match(emoji)
    end

    # Запрет, не называющий того, что запрещает, модель применяет к чему
    # угодно: этот урок уже записан для ENVIRONMENT, где пришлось перечислить
    # выдуманные пути поимённо. Здесь по той же причине названы конкретные
    # обороты, а не «не будь многословен».
    it "называет запрещённые обороты поимённо" do
      expect(described_class::SYSTEM_PROMPT).to include("Great question!", "Happy to help!", "No emoji")
    end
  end
end
