# frozen_string_literal: true

module MiniAgent
  # Насколько заполнено контекстное окно.
  #
  # Собирает вместе три числа, которые до сих пор жили порознь и потому
  # ничего не значили: размер окна (от сервера или из настроек), текущий
  # промпт в токенах (из usage) и max_tokens. Пока их не сложили, каждое
  # выглядело безобидно — а вместе они объясняют оба сбоя, найденных живой
  # проверкой: и «пустой ответ» при max_tokens вполовину окна, и HTTP 400
  # на большом описании проекта.
  #
  # Чистая функция от трёх чисел: ничего не печатает и никуда не ходит.
  class Window
    # Своё место в окне нужно не только истории: под ответ модели должно
    # остаться max_tokens, иначе генерация оборвётся на полуслове. Поэтому
    # «занято» считается как промпт ПЛЮС резерв на ответ — именно эта сумма
    # и упирается в потолок.
    #
    # Порог предупреждения: три четверти. Ниже — обычная работа, выше — пора
    # звать /compact, пока он ещё проходит (после упора он уже не проходит:
    # чтобы свернуть, историю надо отправить целиком).
    WARN_AT = 0.75

    def initialize(size:, prompt_tokens: nil, max_tokens: 0)
      @size = size
      @prompt_tokens = prompt_tokens
      @max_tokens = max_tokens
    end

    attr_reader :size, :max_tokens

    # Известен ли размер окна. Всё остальное имеет смысл только при true:
    # без размера доли считать не от чего.
    def known? = !@size.nil? && @size.positive?

    # Есть ли что показывать: размер известен И сервер прислал usage.
    # Два разных незнания, но для показа последствие одно.
    def measurable? = known? && !@prompt_tokens.nil? && @prompt_tokens.positive?

    # Промпт плюс резерв на ответ — то, что реально претендует на окно.
    def occupied
      return 0 unless measurable?

      @prompt_tokens + @max_tokens
    end

    # Доля занятого в процентах. Может превысить 100: max_tokens вполне
    # бывает больше остатка окна, и это ровно тот случай, который надо
    # показать, а не спрятать округлением вниз.
    def percent
      return 0 unless measurable?

      (occupied * 100.0 / @size).round
    end

    # Сколько токенов остаётся на генерацию после истории. Отрицательное
    # значение означает, что max_tokens в окно уже не помещается: обрыв
    # ответа наступит гарантированно, и виновата не модель.
    def free
      return nil unless measurable?

      @size - @prompt_tokens
    end

    # Место кончается — пора сворачивать диалог.
    def tight? = measurable? && percent >= WARN_AT * 100

    # max_tokens не помещается в остаток окна: длинный ответ упрётся в
    # остаток, а не в лимит. Отдельно от tight?, потому что лечится другим —
    # не /compact, а уменьшением max_tokens (или бо́льшим окном на сервере).
    #
    # Это признак РИСКА, а не приговора: max_tokens — разрешение, а не бронь.
    # Живая проверка при остатке 6035 и лимите 7000 дала полный ответ, потому
    # что модель уложилась в 800 токенов. Сбывается признак на длинном ответе
    # и на рассуждающей модели, где размышления тратят тот же бюджет.
    def starved? = measurable? && free.to_i < @max_tokens
  end
end
