# frozen_string_literal: true

module MiniAgent
  # Откуда берётся значение настройки: опция командной строки → переменная
  # окружения → умолчание. Одно правило на все ключи, без исключений.
  #
  # Выделено из Config порогом Metrics/ClassLength — в десятый раз он указал
  # верно. Config отвечает на вопрос «что это значение значит»: сколько
  # токенов оставить под ответ, какую политику подтверждений выбрать, с какой
  # доли окна сворачивать. Здесь другой вопрос — «задано ли оно вообще и кем»,
  # и ответ на него одинаков для всех ключей. Смешанными эти два вопроса
  # уже подводили: в исходном скрипте base_url и model читались только
  # из ENV и молча игнорировали переданные опции, а max_turns учитывал оба
  # источника, — расхождение, которое ровно потому и не бросалось в глаза,
  # что правило нигде не было записано одним куском.
  class Lookup
    def initialize(options, env, defaults:, keys:)
      @options = options
      @env = env
      @defaults = defaults
      @keys = keys
    end

    # Значение, заданное человеком, либо nil. Умолчание здесь не подставляется
    # намеренно: «не задано» — это ответ, который нужен и Sampling (у его
    # ключей умолчаний нет вовсе), и признаку given?.
    #
    # options.key? вместо проверки на истинность: иначе явное false
    # (флаг --no-allow-unsafe) не смогло бы перебить ALLOW_UNSAFE=true.
    # Пустая строка в переменной окружения считается незаданной — иначе
    # `LLM_MODEL= mini_agent ...` означало бы модель с пустым именем.
    def given(key)
      return @options[key] if @options.key?(key) && !@options[key].nil?

      value = @env[@keys.fetch(key)]
      value.nil? || value.to_s.empty? ? nil : value
    end

    # Задано ли человеком. Нужно там, где есть второе указание того же
    # смысла: политике (--allow-unsafe) и max_tokens (доля от окна).
    def given?(key) = !given(key).nil?

    # Значение с умолчанием. KeyError на ключе без умолчания — защита,
    # а не недосмотр: код, спросивший общим путём то, чего в DEFAULTS нет
    # (температуру, например), обязан ломаться громко, а не получать
    # выдуманное число, которое молча уедет в тело запроса.
    def fetch(key)
      value = given(key)
      value.nil? ? @defaults.fetch(key) : value
    end

    # Булев признак из чего угодно: из флага он приходит уже булевым,
    # из окружения — строкой.
    def bool(key)
      value = fetch(key)
      case value
      when true, false then value
      else %w[true 1 yes].include?(value.to_s.strip.downcase)
      end
    end
  end
end
