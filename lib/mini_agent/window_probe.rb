# frozen_string_literal: true

require "net/http"
require "json"

module MiniAgent
  # Попытка узнать у сервера размер контекстного окна загруженной модели.
  #
  # Само число агенту нужно постоянно: в него упирается и рост истории, и
  # max_tokens, и потолок описания проекта. Но OpenAI-совместимый протокол
  # его не сообщает — ни в /models, ни в ответе на запрос. Единственное,
  # что приходит от сервера, — prompt_tokens в usage, то есть где мы сейчас,
  # без ответа на вопрос «из скольких».
  #
  # У LM Studio значение есть в /api/v1/models — это его собственное
  # расширение, не часть протокола. Отсюда весь характер класса: он ПРОБУЕТ
  # спросить и молча отступает при любой неудаче. Чужой сервер ответит 404
  # или чем угодно ещё, и это не ошибка — просто узнать не вышло. Ошибкой
  # было бы шуметь про необязательный запрос, которого пользователь
  # не заказывал.
  #
  # Значение из --context-window сюда не попадает вовсе: заданное человеком
  # перебивает угаданное, и спрашивать сервер тогда незачем (см. вызов
  # в AgentBuilder).
  class WindowProbe
    # Старый /api/v0/models объявлен устаревшим и не поддерживается: два
    # разбора одного числа разошлись бы при первой правке, а «узнать
    # не вышло» — штатный исход этого класса, и на старой сборке LM Studio
    # он просто наступит чуть чаще.
    PATH = "/api/v1/models"

    # Проба идёт вне очереди на старте, когда человек ждёт первого ответа.
    # Секунда — потолок ожидания необязательной справки: не ответили быстро,
    # значит работаем без неё.
    TIMEOUT = 1

    # Паузы фоновых повторов, в секундах. Растут, и это не украшение:
    # промах на старте почти всегда означает не сбой сети, а модель,
    # которую LM Studio ещё не подняла — она грузится по первому запросу
    # к /chat/completions, то есть ПОСЛЕ нашей пробы. Пять быстрых попыток
    # подряд отстрелялись бы за секунды, все впустую; здесь они растянуты
    # на минуту с небольшим — столько поднимается модель на два десятка
    # гигабайт. Список, а не формула: числа тут подбираются глазами.
    RETRY_DELAYS = [2, 4, 8, 16, 32].freeze

    def initialize(config:, delays: RETRY_DELAYS)
      @config = config
      @delays = delays
    end

    # Возвращает размер окна загруженной модели или nil. Не бросает ничего:
    # неудача пробы не должна мешать работе, ради которой агент запущен.
    def call
      response = fetch
      return nil unless response.is_a?(Net::HTTPSuccess)

      window(JSON.parse(response.body))
    rescue StandardError
      # Сеть, разбор, неожиданный формат — всё это здесь одно и то же:
      # спросить не удалось. Список исключений тут был бы длиннее пользы.
      nil
    end

    # Фоновые повторы после промаха синхронной пробы. Отдаёт первый успех
    # в блок и умирает; ничего не добившись, умирает молча.
    #
    # Поток, а не проверка в цикле ходов: запрос необязательный, и его
    # секундному таймауту нечего делать в горячем пути агента. Возвращается
    # сам Thread — звавший обязан прибрать его за собой, иначе повторы
    # переживут работу, ради которой их заводили.
    def watch(&block)
      Thread.new do
        @delays.each do |delay|
          sleep(delay)
          size = call
          next unless size

          block&.call(size)
          break
        end
      end
    end

    private

    def fetch
      http = Net::HTTP.new(uri.host, uri.port)
      http.use_ssl = uri.scheme == "https"
      http.open_timeout = TIMEOUT
      http.read_timeout = TIMEOUT
      http.request(Net::HTTP::Get.new(uri.path, headers))
    end

    # Путь строится от корня сервера, а не от base_url: /api/v1 — сосед /v1,
    # а не его потомок. Порт и схему берём из адреса, которым и так пользуемся.
    def uri
      @uri ||= URI.parse(@config.base_url).tap do |parsed|
        parsed.path = PATH
        parsed.query = nil
      end
    end

    def headers
      {
        "Content-Type" => "application/json",
        "Authorization" => "Bearer #{@config.api_key}"
      }
    end

    def window(parsed)
      # LM Studio отвечает 200 с полем error в теле на неверный путь —
      # та же ловушка, что и в ModelsRequest. Без этой проверки поле models
      # искалось бы в объекте ошибки.
      return nil if parsed.is_a?(Hash) && parsed["error"]
      return nil unless parsed.is_a?(Hash) && parsed["models"].is_a?(Array)

      size(select(instances(parsed["models"])))
    end

    # Загруженное описывается списком экземпляров у каждой модели, а не
    # плоским признаком: одна и та же модель бывает поднята дважды и
    # с разными окнами. Отсюда и разбор сразу в общий список пар
    # «имя — окно»: дальше выбирать надо среди экземпляров, а не моделей.
    #
    # Имя берётся у экземпляра, а не у модели: обращаемся мы именно к нему,
    # и ключ модели тут запасной вариант на случай, когда сервер его
    # не назвал.
    def instances(models)
      models.flat_map do |model|
        next [] unless model.is_a?(Hash) && model["loaded_instances"].is_a?(Array)

        model["loaded_instances"].filter_map do |instance|
          [instance["id"] || model["key"], context_length(instance)] if instance.is_a?(Hash)
        end
      end
    end

    # max_context_length сознательно не берётся запасным вариантом: у той же
    # модели это 262144 против загруженных 50176. Ошибиться в пять раз
    # в бо́льшую сторону хуже, чем не знать: агент считал бы, что места
    # полно, ровно там, где оно кончилось.
    def context_length(instance)
      instance["config"]["context_length"] if instance["config"].is_a?(Hash)
    end

    # Сначала ищем экземпляр ПО ИМЕНИ и только потом — единственный
    # загруженный.
    #
    # Первая версия брала первый попавшийся, исходя из того, что загруженная
    # модель одна. На живом сервере их оказалось две (qwen с окном 65536 и
    # bonsai с 8192), и при работе со второй агент показывал окно первой —
    # вдвое больше настоящего, то есть ровно та ошибка в бо́льшую сторону,
    # от которой отказались в пользу незнания.
    #
    # Порядок именно такой: имя точнее, но ненадёжно — LM Studio на
    # незнакомое имя молча подставляет загруженную (это уже ловилось
    # в --list-models), поэтому промах по имени означает «работает не та,
    # что названа», и остаётся общий случай. Когда загружен ровно один,
    # он и отвечает, какое бы имя ни стояло в настройках. Когда их
    # несколько, а имя не совпало, — угадывать нечего: молчим.
    def select(instances)
      instances.find { |id, _| id == @config.model } || (instances.first if instances.one?)
    end

    def size(instance)
      size = instance&.last
      size if size.is_a?(Integer) && size.positive?
    end
  end
end
