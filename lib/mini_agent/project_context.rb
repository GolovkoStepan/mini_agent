# frozen_string_literal: true

module MiniAgent
  # Описание проекта, дописываемое к системному промпту.
  #
  # Без него агент выясняет устройство проекта заново на каждом запуске: чем
  # запускаются тесты, куда складывать код, на каком языке комментарии. Это
  # три-четыре хода `ls` и `cat` перед началом работы — и каждый раз одни и те
  # же выводы, потому что история между запусками не живёт.
  #
  # Ищутся два имени: AGENTS.md (складывающееся межинструментальное соглашение)
  # и .mini_agent.md (если в проекте уже лежит AGENTS.md для другого агента, а
  # этому нужно сказать своё). Первое найденное побеждает — склейка двух
  # файлов дала бы противоречивые указания без способа их развести.
  class ProjectContext
    FILENAMES = %w[AGENTS.md .mini_agent.md].freeze

    # Потолок в 20 000 знаков: файл больше — это уже не описание проекта,
    # а его документация, и она вытеснит из контекстного окна саму задачу.
    # Обрезается по границе строки, чтобы не оборвать фразу на середине.
    #
    # Знаки, а не байты, и это не косметика. Платится за описание токенами,
    # а байтов на токен приходится вдвое больше у русского текста, чем у кода
    # (замер на qwen3.6: 5,3 против 3,9), — то есть один и тот же потолок
    # в байтах означал бы разную цену. Знаков на токен приходится почти
    # поровну: 2,95 у Makefile, 3,70 у Ruby, 3,1–3,5 у русского текста.
    MAX_CHARS = 20_000

    # Какую долю окна можно отдать описанию, когда его размер известен.
    #
    # Половину окна уже забронировал ответ модели (Config::WINDOW_SHARE),
    # значит истории достаётся вторая половина — и делить её описание обязано
    # с самим диалогом: задачей, выводом команд, ответами. Отсюда четверть
    # окна, то есть половина оставшегося. Считается от Config::WINDOW_SHARE,
    # а не задано числом: вырастет резерв под ответ — описание обязано
    # ужаться, иначе они вдвоём вытеснят работу, ради которой агент запущен.
    SHARE = (1 - Config::WINDOW_SHARE) / 2

    def self.load(dir = Dir.pwd, window: nil)
      new(dir, window: window).load
    end

    # window — размер контекстного окна в токенах или nil, если он неизвестен.
    # Неизвестен он на любом сервере, кроме LM Studio (см. WindowProbe), и это
    # обычное дело: тогда остаётся один потолок в знаках.
    def initialize(dir = Dir.pwd, window: nil)
      @dir = dir
      @window = window
    end

    # Сколько знаков описания взято и сколько было в файле. Заполняются
    # при load; нужны AgentBuilder, чтобы сказать вслух, что описание урезано.
    # Молчать об этом нельзя: агент знает о проекте не всё, что в файле
    # написано, а по его поведению этого не увидеть — он просто не упомянет
    # того, чего не читал.
    attr_reader :kept, :total

    # Возвращает содержимое файла или nil, если его нет.
    def load
      path = find
      return nil unless path

      content = read(path)
      return nil if content.nil? || content.strip.empty?

      truncate(content)
    end

    # Имя найденного файла — для сообщения пользователю о том, что контекст
    # подхвачен. Молчаливое изменение поведения агента хуже лишней строки
    # в выводе: иначе непонятно, почему он вдруг знает про `make spec`.
    def filename
      path = find
      path && File.basename(path)
    end

    # Описание урезано, то есть модель видит не весь файл.
    def truncated? = !@total.nil? && @kept < @total

    # Что урезало описание: маленькое окно (:window) или общий потолок
    # (:ceiling). Причины разные, и лечения у них тоже разные: окно
    # раздвигается загрузкой модели с бо́льшим ctx на сервере, а потолок этим
    # не сдвинуть — файл придётся сокращать. Найдено живой проверкой: при
    # окне 60416 описание резал потолок, а сообщение винило окно и посылало
    # чинить сервер вместо файла.
    def limited_by = window_limit && window_limit < MAX_CHARS ? :window : :ceiling

    private

    # Потолок в знаках для этого запуска: меньшее из доли окна и общего
    # потолка. Потолок не отменяется большим окном: «слишком длинно для
    # описания проекта» и «не влезает в окно» — разные вещи, и просторное
    # окно не делает документацию описанием.
    def limit = [window_limit, MAX_CHARS].compact.min

    # Доля окна в знаках или nil, когда размер окна неизвестен. Неизвестен он
    # на любом сервере, кроме LM Studio, и это обычное дело — тогда остаётся
    # один потолок.
    def window_limit
      return nil if @window.nil?

      (@window * SHARE * Window::CHARS_PER_TOKEN).to_i
    end

    def find
      @find ||= FILENAMES.lazy.map { |name| File.join(@dir, name) }.find { |path| File.file?(path) }
    end

    # Нечитаемый файл — не повод падать: агент прекрасно работает и без
    # описания проекта, а разбираться с правами посреди задачи незачем.
    #
    # scrub на границе с внешним миром, а не перед отправкой: негодные байты
    # в файле — такая же обыденность, как в выводе команды (см. ProcessRunner),
    # а всплывают они позже и невнятно, JSON::GeneratorError при сборке тела
    # запроса. Заодно после него можно резать строку по знакам, не боясь
    # разрубить многобайтовый символ.
    def read(path)
      File.read(path).scrub("")
    rescue SystemCallError, IOError
      nil
    end

    # Отбрасывание последней строки убирает оборванную фразу, но полагаться
    # на это в файле без переводов строк нельзя — там останется обрыв
    # на полуслове, и пометка о нём тем более обязательна.
    def truncate(content)
      @total = content.size
      @kept = content.size
      return content if content.size <= limit

      kept = content[0, limit].to_s.lines[0..-2].to_a.join
      @kept = kept.size
      kept + Messages::CONTEXT_TRUNCATED
    end
  end
end
