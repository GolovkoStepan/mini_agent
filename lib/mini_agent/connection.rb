# frozen_string_literal: true

require "net/http"

module MiniAgent
  # Жизнь HTTP-соединения с сервером модели: поднять, держать открытым на всю
  # работу, погасить.
  #
  # Выделено из LLMClient одиннадцатым сработавшим Metrics/ClassLength, и порог
  # снова указал верно: у остального клиента задача — что спросить у сервера
  # и как разобрать ответ, а здесь ни одного вопроса и ни одного ответа, только
  # сокет. Появилось это как отдельная задача не сразу: пока соединение просто
  # поднималось и закрывалось, оно было деталью запроса, — но с общим сроком
  # на ответ у него завёлся третий исход (оборвали чтение, соединение
  # непригодно), и деталью это быть перестало.
  #
  # Таймауты живут здесь по той же причине: это свойства соединения, а не
  # разговора.
  class Connection
    # Ожидание ответа настраивается, а открытие соединения — нет: сервер либо
    # отзывается сразу, либо его нет, и десяти секунд на это хватает при любой
    # скорости модели. Медленной бывает генерация, а не TCP.
    OPEN_TIMEOUT = 10

    def initialize(config:)
      @config = config
      @http = nil
    end

    # Держит одно соединение на всё время работы блока.
    def open
      connection = build
      connection.start unless connection.started?
      @http = connection
      yield
    ensure
      drop
    end

    # Поднимается лениво: в исходном скрипте вызов run без предварительного
    # start_http падал с NoMethodError на nil.
    def http = @http ||= build

    # Соединение после оборванного потока непригодно: в сокете осталась
    # недочитанная половина ответа, и следующий запрос разобрал бы её как
    # свою. Гасим и забываем — http поднимет новое лениво.
    #
    # Тем же способом соединение закрывается и по окончании работы: разницы
    # между «оборвали» и «закончили» для сокета нет, а два способа закрыть
    # одно и то же разошлись бы при первой правке.
    def drop
      @http&.finish if @http&.started?
    rescue IOError, SystemCallError
      # Соединение и так мертво — закрывать нечего.
      nil
    ensure
      @http = nil
    end

    private

    def build
      uri = @config.chat_uri
      http = Net::HTTP.new(uri.host, uri.port)
      http.use_ssl = @config.use_ssl?
      http.open_timeout = OPEN_TIMEOUT
      # ЭТО НЕ СРОК НА ОТВЕТ ЦЕЛИКОМ. Net::HTTP отмеряет read_timeout на
      # каждое чтение, а не на весь ответ, поэтому в потоке он ограничивает
      # ПАУЗЫ МЕЖДУ КУСКАМИ: пока сервер шлёт токены, таймер сбрасывается
      # бесконечно. Общий срок отмеряет StreamRequest, тем же числом.
      # В непотоковом режиме их можно не разделять — там сервер молчит до
      # конца генерации, и пауза до первого куска и есть всё время ответа.
      http.read_timeout = @config.llm_timeout
      http
    end
  end
end
