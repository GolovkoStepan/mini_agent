# frozen_string_literal: true

module MiniAgent
  # Напоминание модели, чем она вообще занята.
  #
  # Задача сказана один раз и уезжает вверх истории: к двадцатому ходу между
  # ней и текущим запросом лежат десятки выводов команд, и модель отвечает
  # уже им, а не поручению — придумывает недостающее, объявляет сделанным
  # соседнее, берётся за то, чего не просили. Лечится тем же способом, каким
  # в проекте уже лечится забывчивость: PLAN_INSTRUCTION повторяется с каждой
  # задачей, STOP_MAX_TURNS приходит user-сообщением в конец истории.
  # Здесь то же — исходная задача дословно, последним сообщением перед
  # запросом, то есть там, где внимание модели наибольшее.
  #
  # Повторяется дословно, а не пересказом: пересказ пришлось бы у кого-то
  # спрашивать, то есть тратить ход и давать модели ещё один шанс
  # нафантазировать (тот же довод, по которому одобренный план не сворачивают
  # в резюме).
  #
  # Разметка <task> помогает модели отличить напоминание от новой задачи,
  # но защитой не является — ровно как <project_context> и <approved_plan>.
  class TaskAnchor
    def initialize(config:, usage: nil)
      @config = config
      @usage = usage
    end

    # Кладёт якорь в историю и отвечает, положил ли. Признак нужен не агенту,
    # а тестам и будущему журналу: сам цикл ходов от него не зависит.
    #
    # Порог тот же, что у сворачивания (Config#compact_at), и это не
    # экономия на настройке. Своим порогом якорь ставился бы задолго до
    # тесноты — то есть добавлял бы по сообщению на ход через всю сессию,
    # ровно там, где место ещё есть и забывать нечего.
    #
    # Отсюда же и то, как якорь уживается с автоматическим сворачиванием:
    # то стоит на том же пороге и срабатывает первым, а сборка новой истории
    # обнуляет «контекст сейчас» — заполнение становится неизмеримым, и якорь
    # ход пропускает. Это верно и по делу: сразу после сворачивания задача
    # лежит в свежем резюме близко к концу. Каждый ход подряд якорь ставится
    # только тогда, когда сворачивание сдалось до конца сессии, — то есть
    # когда история не сжимается, а модель всё равно должна помнить, зачем
    # её позвали.
    def call(conversation, task)
      return false if task.to_s.empty?
      return false unless ContextReport.new(conversation, usage: @usage, config: @config).window.tight?

      conversation.user(format(Messages::TASK_ANCHOR, task: task))
      true
    end
  end
end
