# frozen_string_literal: true

module MiniAgent
  # Режим планирования: агент изучает проект и предлагает порядок действий,
  # ничего при этом не меняя.
  #
  # Состояние сессии, а не четвёртая политика подтверждений. Все три политики
  # отвечают на один вопрос — спрашивать ли разрешения, — и различаются только
  # ответом на него. Здесь вопрос другой: выполнять ли вообще. Вдобавок это
  # состояние временное по самому замыслу — план на то и план, чтобы его
  # одобрили и выполнили в той же сессии, — а политика, которую переключают
  # посреди работы, перестала бы быть политикой.
  class PlanMode
    def initialize(enabled: false)
      @enabled = enabled
      @plan = nil
    end

    # Текст последнего плана. Хранится здесь, а не выковыривается из истории
    # последним ответом модели: автоматическое сворачивание заменяет историю
    # целиком, и план ушёл бы в резюме ровно так же, как уходила туда свежая
    # задача (см. Agent#run). Потерять при этом можно единственный результат
    # всей проделанной работы.
    attr_accessor :plan

    def on? = @enabled

    def enable
      @enabled = true
      self
    end

    def disable
      @enabled = false
      self
    end

    # Планирование — это не «ничего не выполнять», а «выполнять только
    # заведомо читающее»: план по незнакомому проекту нельзя составить,
    # не прочитав его, и запрет на всё превратил бы план в выдумку.
    #
    # Спрашивается признак, а не команда, и это не мелочь. Про команду
    # приходится гадать разбором строки (ReadOnly — тот самый список, свой
    # заводить нельзя: второй разошёлся бы с первым при первой правке). Цена
    # гадания измерена: на живом исследовании этого репозитория (17 команд)
    # ReadOnly отверг 3 — два `find` и один `cat … 2>/dev/null`; обе формы
    # названы модели в PLAN_INSTRUCTION, иначе она узнаёт о них только
    # отказом, а отказ стоит хода. Про файловый инструмент гадать не надо
    # вовсе — read_file знает про себя, что он читает. Правило же на оба
    # случая одно и живёт здесь.
    def permits?(read_only:) = !on? || read_only
  end
end
